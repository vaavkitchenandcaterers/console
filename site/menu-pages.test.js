import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { loadMenus, loadChrome } from '../tools/build-menu-pages.mjs';
import { renderCategoryPage, slug } from '../tools/menu-page-template.mjs';

const CATS = ['tiffin', 'lunch', 'dinner'];
const menus = loadMenus();
const chrome = loadChrome();

const pageFor = cat => readFileSync(new URL(`./menu/${cat}/index.html`, import.meta.url), 'utf8');
const everyMenu = () => CATS.flatMap(cat => menus[cat].menus.map(m => ({ cat, m })));

describe('generated menu category pages', () => {
  it('each committed page is byte-identical to what the generator produces', () => {
    for (const cat of CATS) {
      const expected = renderCategoryPage(cat, menus[cat], chrome);
      expect(pageFor(cat), `menu/${cat}/index.html is stale — run \`npm run build:menu\``).toBe(expected);
    }
  });

  it('every one of the 66 set menus appears on exactly one category page', () => {
    const pages = Object.fromEntries(CATS.map(c => [c, pageFor(c)]));
    for (const { cat, m } of everyMenu()) {
      const on = CATS.filter(c => pages[c].includes(`<h2>${m.name}</h2>`));
      expect(on, `${m.name} should be on ${cat} only, found on: ${on.join(', ') || 'nothing'}`).toEqual([cat]);
    }
  });

  it('every dish in the dataset is present in its category page', () => {
    for (const cat of CATS) {
      const html = pageFor(cat);
      const missing = [];
      for (const m of menus[cat].menus) {
        for (const [, items] of m.groups) {
          for (const dish of items) {
            const escaped = dish.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
            if (!html.includes(`<li>${escaped}</li>`)) missing.push(`${m.name}: ${dish}`);
          }
        }
      }
      expect(missing, `${cat} page is missing dishes`).toEqual([]);
    }
  });

  it('the whole dish count on each page matches the dataset', () => {
    const counts = { tiffin: 184, lunch: 273, dinner: 518 };
    for (const cat of CATS) {
      const html = pageFor(cat);
      let n = 0;
      for (const block of html.matchAll(/<ul class="set-dishes">([\s\S]*?)<\/ul>/g)) {
        n += (block[1].match(/<li>/g) || []).length;
      }
      const fromData = menus[cat].menus.reduce((t, m) => t + m.groups.reduce((k, g) => k + g[1].length, 0), 0);
      expect(n, `${cat} rendered dish count`).toBe(fromData);
      expect(n, `${cat} dish count drifted from the recorded baseline`).toBe(counts[cat]);
    }
  });

  it('slugs are unique across the dataset, so the #anchors cannot collide', () => {
    const slugs = everyMenu().map(({ m }) => slug(m.name));
    expect(new Set(slugs).size, `duplicate slugs: ${slugs.filter((s, i) => slugs.indexOf(s) !== i)}`).toBe(slugs.length);
  });

  it('every set has an id anchor matching its slug', () => {
    for (const cat of CATS) {
      const html = pageFor(cat);
      for (const m of menus[cat].menus) {
        expect(html, `${cat} missing anchor for ${m.name}`).toContain(`<article class="set" id="${slug(m.name)}">`);
      }
    }
  });

  it('no generated page reintroduces a placeholder href', () => {
    for (const cat of CATS) {
      expect(pageFor(cat), `${cat} has href="#"`).not.toContain('href="#"');
    }
  });

  it('every generated page carries the do-not-edit banner and exactly one h1', () => {
    for (const cat of CATS) {
      const html = pageFor(cat);
      expect(html.startsWith('<!-- GENERATED by tools/build-menu-pages.mjs'), `${cat} banner`).toBe(true);
      expect((html.match(/<h1/g) || []).length, `${cat} h1 count`).toBe(1);
    }
  });

  it('the CSP matches /menu/ byte for byte, so the pages cannot drift apart', () => {
    const re = /<meta http-equiv="Content-Security-Policy"[^>]*>/;
    const base = readFileSync(new URL('./menu/index.html', import.meta.url), 'utf8').match(re)[0];
    for (const cat of CATS) {
      expect(pageFor(cat).match(re)?.[0], `${cat} CSP`).toBe(base);
    }
  });

  it('/menu/ links to all three category pages and they are in the sitemap', () => {
    const hub = readFileSync(new URL('./menu/index.html', import.meta.url), 'utf8');
    const sitemap = readFileSync(new URL('./sitemap.xml', import.meta.url), 'utf8');
    for (const cat of CATS) {
      expect(hub, `/menu/ does not link to ${cat}`).toContain(`href="/menu/${cat}/"`);
      expect(sitemap, `sitemap missing ${cat}`).toContain(`/menu/${cat}/`);
    }
  });
});
